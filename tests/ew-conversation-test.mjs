async function run() {
  console.log("=== EW Conversation Quality Suite ===");
  if (!SUPABASE_URL || !SERVICE_KEY) { console.log("Missing Supabase env"); process.exit(1); }

  // Ensure a lead exists for the phone
  await sb("/leads", {
    method: "POST",
    headers: { Prefer: "return=representation,resolution=merge-duplicates" },
    body: JSON.stringify({ phone_number: PHONE, full_name: "EW Conversation Test", status: "new", opt_in: true }),
  }).catch(() => {});

  // ── GATE: probe whether the EW workflow is answering ──────────────────────
  currentPillar = "gate";
  await cleanConvo();
  const since = new Date().toISOString();
  await sendWebhook(waPayload("Hi, do you sell abayas?"));
  const probe = await waitReply("Hi, do you sell abayas?", since, REPLY_TIMEOUT);
  if (!probe) {
    warn("GATE: no AI reply received", `workflow unreachable/inactive or OpenRouter 402 — all ${SCENARIOS.length} scenarios blocked`);
    return finish();
  }
  if (!probe.message_category) {
    warn("GATE: responder did NOT write message_category", `telecom workflow likely answered — EW workflow not active. Blocked ${SCENARIOS.length} scenarios`);
    console.log(`      ↳ probe reply: ${(probe.ai_response || "").slice(0, 140)}`);
    return finish();
  }
  pass("GATE: EW workflow responding", `category=${probe.message_category}`);

  // ── Department matrix ─────────────────────────────────────────────────────
  for (const s of SCENARIOS) {
    currentPillar = s.dept;
    await cleanConvo();
    await new Promise((r) => setTimeout(r, 800));
    const sinceI = new Date().toISOString();
    const status = await sendWebhook(waPayload(s.send));
    if (status !== 200) { fail(`${s.dept}: ${s.name}`, `webhook HTTP ${status}`); continue; }
    const convo = await waitReply(s.send, sinceI);
    if (!convo) { fail(`${s.dept}: ${s.name}`, "no ai_response within timeout"); continue; }
    const reply = (convo.ai_response || "").toLowerCase();
    const issues = [];
    const allowed = s.category ? [].concat(s.category) : null;
    if (allowed && !allowed.includes(convo.message_category))
      issues.push(`category=${convo.message_category || "null"} expected ${allowed.join("|")}`);
    if (s.mustContainAny && !s.mustContainAny.some((k) => reply.includes(k)))
      issues.push(`missing keywords [${s.mustContainAny.join("|")}]`);
    if (s.mustNotContain && s.mustNotContain.some((k) => reply.includes(k.toLowerCase())))
      issues.push(`forbidden content present`);
    if (!convo.message_category) issues.push("message_category null");
    if (issues.length) fail(`${s.dept}: ${s.name}`, `${issues.join("; ")} | reply: ${reply.slice(0, 90)}`);
    else pass(`${s.dept}: ${s.name}`, `cat=${convo.message_category}`);
  }

  // ── Human takeover sentinel ────────────────────────────────────────────────
  currentPillar = "takeover";
  try {
    const appSecret = process.env.APP_SECRET;
    const lead = await sb(`/leads?phone_number=eq.${PHONE}&select=id&limit=1`);
    if (lead.body?.length && appSecret) {
      const h = await fetch(`${BASE_URL}/api/handover`, {
        method: "POST",
        headers: { "Content-Type": "application/json", Authorization: `Bearer ${appSecret}` },
        body: JSON.stringify({ phone: PHONE, take_over: true, by: "ew-test" }),
      });
      if (h.status === 200) {
        await cleanConvo();
        const sinceT = new Date().toISOString();
        await sendWebhook(waPayload("Are you still there?"));
        await new Promise((r) => setTimeout(r, 12000));
        const rows = await sb(`/conversations?phone_number=eq.${PHONE}&created_at=gte.${sinceT}&select=id,incoming_message,ai_response,message_category`);
        const hit = (rows.body || []).find((c) => c.incoming_message === "Are you still there?");
        if (!hit) warn("takeover: message logged", "no conversation row — check workflow takeover branch");
        else if (hit.ai_response && /order|payment|handover|human|assist/i.test(hit.ai_response) && hit.ai_response.length < 200) {
          pass("takeover: sentinel logged, no AI reply", `"${hit.ai_response.slice(0, 60)}"`);
        } else if (!hit.ai_response || hit.ai_response.length < 10) {
          warn("takeover: logged but no sentinel text", JSON.stringify(hit).slice(0, 120));
        } else fail("takeover: AI replied during human control", hit.ai_response.slice(0, 100));
        await fetch(`${BASE_URL}/api/handover`, {
          method: "POST",
          headers: { "Content-Type": "application/json", Authorization: `Bearer ${appSecret}` },
          body: JSON.stringify({ phone: PHONE, take_over: false, by: "ew-test" }),
        });
      } else warn("takeover setup", `handover API HTTP ${h.status}`);
    } else warn("takeover setup", "no test lead or APP_SECRET");
  } catch (e) { fail("takeover", e.message); }

  await cleanConvo();
  finish();
}

function finish() {
  const summary = {
    total: results.length,
    pass: results.filter((r) => r.status === "PASS").length,
    fail: results.filter((r) => r.status === "FAIL").length,
    warn: results.filter((r) => r.status === "WARN").length,
    ran_at: new Date().toISOString(),
  };
  fs.writeFileSync(RESULTS_FILE, JSON.stringify({ summary, results }, null, 2));
  console.log(`\n=== ${summary.pass} PASS / ${summary.fail} FAIL / ${summary.warn} WARN ===`);
  console.log(`Results → ${RESULTS_FILE}`);
  process.exit(summary.fail ? 1 : 0);
}

run().catch((e) => { console.error(e); rec("FAIL", "suite crashed", e.message); finish(); });
