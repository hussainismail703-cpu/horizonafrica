#!/usr/bin/env node
/**
 * Eastern Wear — Layla Conversation Quality Suite (AI-gated)
 * (full-suite-test-plan.md — Suite A2 + business-rules knowledge)
 *
 * Department classification matrix (§4.2) + business-rules knowledge (§4.8) +
 * handover + scoring guardrails. Sends Meta-format webhooks to the local
 * proxy → n8n → OpenRouter → Supabase conversations.
 *
 * GATE: requires OpenRouter credits AND the Eastern Wear workflow reachable
 * at N8N_WEBHOOK_URL (activated or test-webhook repoint). The suite sends a
 * probe first; if the responder doesn't write `message_category` (i.e. the
 * telecom workflow answered or nothing answered), all tests are reported
 * WARN-blocked, not failed.
 *
 * Usage:
 *   node --env-file=.env.local tests/ew-conversation-test.mjs
 *   EW_TEST_PHONE=2782xxxxxxx node --env-file=.env.local tests/ew-conversation-test.mjs
 *
 * Safety: only the test phone is used; conversation rows for it are cleaned
 * between scenarios. No real outbound send occurs from this script — WhatsApp
 * replies are generated by n8n only if the workflow is live.
 */

import fs from "fs";
import path from "path";
import { webhookHeaders } from "./lib/webhook.mjs";

function loadEnvFile(filePath) {
  if (!fs.existsSync(filePath)) return;
  for (const line of fs.readFileSync(filePath, "utf8").split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Za-z0-9_]+)\s*=\s*(.*?)\s*$/);
    if (m && !process.env[m[1]]) process.env[m[1]] = m[2].replace(/^['"]|['"]$/g, "");
  }
}
loadEnvFile(path.join(process.cwd(), ".env.local"));

const BASE_URL = process.env.TEST_TARGET || "http://localhost:3000";
const SUPABASE_URL = process.env.NEXT_PUBLIC_SUPABASE_URL;
const SERVICE_KEY = process.env.SUPABASE_SERVICE_ROLE_KEY;
const PHONE = process.env.EW_TEST_PHONE || "27823725575";
const REPLY_TIMEOUT = parseInt(process.env.EW_REPLY_TIMEOUT_MS || "60000", 10);
const RESULTS_FILE = path.join(process.cwd(), "tests", "ew-conversation-results.json");

const results = [];
let currentPillar = "setup";
function rec(status, name, detail = "") {
  results.push({ pillar: currentPillar, name, status, detail });
  const icon = { PASS: "✅", FAIL: "❌", WARN: "⚠️ " }[status];
  console.log(`  ${icon} ${name}${detail ? ` — ${detail.slice(0, 110)}` : ""}`);
}
const pass = (n, d) => rec("PASS", n, d);
const fail = (n, d) => rec("FAIL", n, d);
const warn = (n, d) => rec("WARN", n, d);

async function sb(pathname, options = {}) {
  const res = await fetch(`${SUPABASE_URL}/rest/v1${pathname}`, {
    ...options,
    headers: {
      apikey: SERVICE_KEY, Authorization: `Bearer ${SERVICE_KEY}`,
      "Content-Type": "application/json", Prefer: "return=representation",
      ...options.headers,
    },
  });
  const text = await res.text();
  try { return { status: res.status, body: text ? JSON.parse(text) : null }; }
  catch { return { status: res.status, body: text }; }
}

function waPayload(text, phone = PHONE) {
  return {
    object: "whatsapp_business_account",
    entry: [{ id: "EWTEST", changes: [{ field: "messages", value: {
      messaging_product: "whatsapp",
      metadata: { display_phone_number: "27757774389", phone_number_id: "1257101724147822" },
      contacts: [{ profile: { name: "EW Test" }, wa_id: phone }],
      messages: [{ from: phone, id: `wamid.EW${Date.now()}${Math.random().toString(36).slice(2, 6)}`, timestamp: `${Math.floor(Date.now() / 1000)}`, type: "text", text: { body: text } }],
    } }] }],
  };
}

async function sendWebhook(payload) {
  const raw = JSON.stringify(payload);
  const res = await fetch(`${BASE_URL}/api/whatsapp-webhook`, {
    method: "POST",
    headers: { "Content-Type": "application/json", ...webhookHeaders(raw) },
    body: raw,
  });
  return res.status;
}

async function cleanConvo() {
  await sb(`/conversations?phone_number=eq.${PHONE}`, { method: "DELETE" }).catch(() => {});
}

async function waitReply(messageText, sinceIso, timeout = REPLY_TIMEOUT) {
  const deadline = Date.now() + timeout;
  while (Date.now() < deadline) {
    const r = await sb(`/conversations?phone_number=eq.${PHONE}&created_at=gte.${sinceIso}&order=created_at.desc&limit=5&select=id,incoming_message,ai_response,message_category,created_at`);
    const rows = Array.isArray(r.body) ? r.body : [];
    const hit = rows.find((c) => c.incoming_message === messageText && c.ai_response);
    if (hit) return hit;
    await new Promise((r2) => setTimeout(r2, 2000));
  }
  return null;
}

// scenario: { dept, send, category?, mustContainAny?, mustNotContain?, alertHint }
